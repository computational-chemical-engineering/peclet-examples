#!/usr/bin/env python3
"""Write the TBFsolver case directory for the bubble-column benchmark from `case.py`.

    python make_tbf_case.py                      # -> ../tbfsolver/case  (the production specs)
    python make_tbf_case.py --out DIR --tf 0.4 --dtout 0.1     # a short smoke-test case

Every number comes from `case.py`, so the peclet and TBFsolver runs cannot drift apart. The file
format is that of the one shipped TBFsolver case (`channel_18/specs`): one `name value` pair per
line, the name ending at the FIRST blank, the value read with a fixed Fortran edit descriptor
(`src/fields/formats.f90`: I6 for integers, L7 for logicals, ES25.15E3 for reals — so reals are
always written with a decimal point and a `d` exponent, and fit in 25 characters). Lines whose
first token is not a known name (comments, blank lines) are skipped by the parser.

What the case is, in TBFsolver's terms:

  * A closed (batch) column: `flowCtrl 2` with `flow_rate 0` and `gCH = G`, `g = 0`. Gravity is
    along +x and balanced by the mean weight, so the x-momentum source per unit volume is
    (rho - <rho>) G and bubbles rise towards -x (`auxiliaryRoutines.f90::setPressGrad` applies
    the same -<rho> G mean pressure gradient for flowCtrl 2 and 3, `momentumEqn.f90::addSource`).
    On top of that, after every projection `auxiliaryRoutines.f90::setFlowRate` adds one uniform
    du = -sum(u_x dV)/V to every u_x face, so the net VOLUME flux through each x-section stays
    exactly zero — what a batch column with a closed bottom has.
    Why not `flowCtrl 3` (available as `--open`): it only fixes the mean pressure gradient at
    the mixture weight and leaves the net flux free. Liquid descending along the walls then feels
    an upward wall friction that nothing balances, and the column develops a net upflow until
    the net wall shear vanishes: measured <rho u>_x = -0.0056 per unit time (t = 2..7, the
    wall-shear estimate mu u_1/(h/2) gives 0.0053), mean liquid velocity -0.035 by t = 7 and
    still growing (the stopped run in `tbfsolver/run_open/`).
  * x and z periodic, y bounded by no-slip walls: FAST_MODE's Poisson solver is FFT in x and z
    and tridiagonal in y, and requires wrap_x = wrap_z = .true. and py = 1 (`mpiControl.f90`).
  * `method 2` (bubble array, nbx-fastest loop) with the explicit centres in
    `specs/bubblePositions` — read by the local patch to `src/VOF/vofBlocks.f90`; the unpatched
    code would silently put the bubbles on the unperturbed lattice instead.
  * Fluid at rest, pressure zero: every field uses `init_opt 1` (uniform value), so the input
    folder `0/` only has to exist.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import case

HEADER = ("! bubble-column benchmark - GENERATED by benchmarks/bubble-column/scripts/"
          "make_tbf_case.py from case.py; edit case.py, not this file.\n\n")


def fr(x):
    """A real in TBFsolver's spec format: decimal point, `d` exponent, <= 25 characters."""
    s = f"{float(x):.16e}".replace("e", "d")
    assert len(s) <= 25, s
    return s


def fb(x):
    return ".TRUE." if x else ".FALSE."


def write(path, body):
    with open(path, "w") as f:
        f.write(HEADER + body.strip("\n") + "\n")


def bc_block(prefix, codes):
    """The six boundary patches (left,right,bottom,top,back,front = -x,+x,-y,+y,-z,+z)."""
    lines = [f"b{prefix}{i} {c}" for i, c in enumerate(codes, 1)]
    lines += [""] + [f"bv{prefix}{i} 0.d0" for i in range(1, 7)]
    return "\n".join(lines)


# x and z periodic (3); y walls: velocity fixedValue 0 (1), colour and pressure zero-gradient (2)
BC_SCALAR = (3, 3, 2, 2, 3, 3)
BC_VELOCITY = (3, 3, 1, 1, 3, 3)


def make(out, tf, dtout, px, pz, process_averages, ts, closed=True):
    specs = os.path.join(out, "specs")
    os.makedirs(os.path.join(specs, "fstart_bc"), exist_ok=True)
    os.makedirs(os.path.join(out, "0"), exist_ok=True)       # input_folder 0 must exist
    keep = os.path.join(out, "0", ".gitkeep")
    if not os.path.exists(keep):
        open(keep, "w").close()

    if case.NX % px or case.NZ % pz:
        raise SystemExit(f"px={px} must divide nx={case.NX} and pz={pz} must divide nz={case.NZ}")

    write(os.path.join(specs, "mesh"), f"""
Lx {fr(case.LX)}
Ly {fr(case.LY)}
Lz {fr(case.LZ)}

isXunif .TRUE.
isYunif .TRUE.
isZunif .TRUE.

nx {case.NX}
ny {case.NY}
nz {case.NZ}
""")

    write(os.path.join(specs, "decompose"), f"""
! FAST_MODE: py must be 1 (y is the tridiagonal pencil); px | nx, pz | nz
px {px}
py 1
pz {pz}

wrap_x .true.
wrap_y .false.
wrap_z .true.
""")

    write(os.path.join(specs, "parameters"), f"""
! Loisy et al. JFM 2017 case E1: Ar {case.AR}, Bo {case.BO}; D = rho_l = g = 1
rhol {fr(case.RHO_L)}
rhog {fr(case.RHO_G)}
mul {fr(case.MU_L)}
mug {fr(case.MU_G)}
sigma {fr(case.SIGMA)}

! gCH = gravity along +x (balanced by a -<rho> gCH mean pressure gradient); g = along y (none)
gCH {fr(case.G)}
g 0.d0
""")

    if closed:
        # zero net VOLUME flux: after every step a uniform correction restores sum(ux dV) = 0
        # (auxiliaryRoutines.f90::setFlowRate) on top of the same -<rho> g mean pressure gradient
        write(os.path.join(specs, "flowControl"), """
! 2 = fixed flow rate; 0 = a closed column (zero net volume flux through every x-section)
flowCtrl 2
read_flow_rate .TRUE.
flow_rate 0.d0
""")
    else:
        # mean pressure gradient fixed at the mixture weight <rho> G; the net flux is free and is
        # driven by the net wall shear until that vanishes (NOT a closed column)
        write(os.path.join(specs, "flowControl"), """
! 3 = balance gravity force - fully periodic box (g is along x)
flowCtrl 3
""")

    write(os.path.join(specs, "flowSolver"), """
! 2 = two-phase flow mode
flow_solver 2
""")

    write(os.path.join(specs, "initVelocity"), """
! fluid initially at rest (no channel-flow perturbation)
perturbed_parabolic .FALSE.
icA 0.d0
""")

    write(os.path.join(specs, "schemes"), """
! as channel_18: AB2 in time, QUICK convection
time_scheme 0
convection_scheme 2
""")

    # FAST_MODE does not use the MG/PCG settings; channel_18's values, so the file is complete
    write(os.path.join(specs, "pcg_solver"), """
nLevels 5
nPreSweep 2
nPostSweep 4

tolMG 4.d-1
maxIterMG 100
fullInfoMG .F.

tolPCG 1.d-10
maxIterPCG 100
fullInfoPCG .F.
""")

    write(os.path.join(specs, "timeControl"), f"""
Tf {fr(tf)}
dt 1.d-3
! writeInterval -1: output by time only, at the first step with t >= k*dtout
writeInterval -1
dtout {fr(dtout)}
input_folder 0

! setTimeStep: dt <= min(viscous/2, capillary/2.5) limits; adaptive: CFL (sum over components)
setTimeStep .T.
adaptiveTimeStep .T.
cflMax 1.d-1

! plane statistics (time averages from Ts on, written with every snapshot)
process_averages {fb(process_averages)}
Ts {fr(ts)}

Tr 1.d-1
isRampUp .F.

vofBlocksRedInterval 1.d-1
restart_boxes .F.
""")

    write(os.path.join(specs, "initBubbles"), f"""
! method 2 = bubble array (nbx fastest); centres overridden by specs/bubblePositions
method 2
nbx {case.NBX}
nby {case.NBY}
nbz {case.NBZ}
R {fr(case.R)}
nref 50

random_distr .FALSE.
""")

    with open(os.path.join(specs, "bubblePositions"), "w") as f:
        f.writelines(f"{c[0]:.12f} {c[1]:.12f} {c[2]:.12f}\n" for c in case.bubble_centres())

    bc = os.path.join(specs, "fstart_bc")
    for name in ("c", "psi"):
        write(os.path.join(bc, name), f"""
grid_type cl

! init_opt 1: uniform initial value iv (c is then filled by the VOF bubble blocks)
init_opt 1
iv 0.d0

! 1 fixedValue, 2 normalGradient, 3 periodic; order left,right,bottom,top,back,front
{bc_block("", BC_SCALAR)}
""")

    ublocks = []
    for d in "xyz":
        ublocks.append(f"! ------- u{d}\n" + bc_block(d, BC_VELOCITY))
    write(os.path.join(bc, "u"), """
gridx_type sx
gridy_type sy
gridz_type sz

! init_opt 1: fluid at rest
init_opt 1
ivx 0.d0
ivy 0.d0
ivz 0.d0

! 1 fixedValue, 2 normalGradient, 3 periodic; order left,right,bottom,top,back,front
""" + "\n\n".join(ublocks))

    print(f"wrote {out}")
    print(f"  {case.summary()}")
    print(f"  Tf {tf}, dtout {dtout}, decomposition {px} x 1 x {pz} = {px*pz} ranks, "
          f"process_averages {process_averages} from Ts {ts}, "
          f"{'flowCtrl 2 (closed, zero net flux)' if closed else 'flowCtrl 3 (weight-balanced)'}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=os.path.join(HERE, "..", "tbfsolver", "case"))
    ap.add_argument("--tf", type=float, default=case.T_END)
    ap.add_argument("--dtout", type=float, default=case.DT_OUT)
    ap.add_argument("--px", type=int, default=4)
    ap.add_argument("--pz", type=int, default=2)
    ap.add_argument("--ts", type=float, default=case.T_STATS)
    ap.add_argument("--no-averages", action="store_true")
    ap.add_argument("--open", action="store_true",
                    help="flowCtrl 3 (weight-balanced, net flux free) instead of the closed "
                         "column (flowCtrl 2, zero net volume flux)")
    a = ap.parse_args()
    make(os.path.normpath(a.out), a.tf, a.dtout, a.px, a.pz, not a.no_averages, a.ts,
         not a.open)


if __name__ == "__main__":
    main()
